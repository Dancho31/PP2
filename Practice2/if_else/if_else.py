# Example 1: Basic if-else
age = 15
if age >= 18:
    print("Adult")
else:
    print("Child")   # Prints this

# Example 2: Even or odd
number = 7
if number % 2 == 0:
    print("Even")
else:
    print("Odd")     # Prints this

# Example 3: Password length
password = "abc"
if len(password) >= 6:
    print("Good password")
else:
    print("Too short")  # Prints this

# Example 4: Check list
items = []
if items:
    print("Shopping needed")
else:
    print("No shopping")  # Prints this

# Example 5: Grade check
score = 45
if score >= 50:
    print("Pass")
else:
    print("Fail")   # Prints this
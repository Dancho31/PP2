# Example 1: One line if-else
age = 20
print("Adult") if age >= 18 else print("Child")  # Adult

# Example 2: Simple condition
is_raining = True
action = "Stay home" if is_raining else "Go out"
print(action)  # Stay home

# Example 3: Check number
number = 7
print("Even") if number % 2 == 0 else print("Odd")  # Odd

# Example 4: Temperature
temp = 25
feeling = "Hot" if temp > 30 else "OK"
print(feeling)  # OK

# Example 5: Empty check
text = ""
message = "Empty" if not text else "Has text"
print(message)  # Empty
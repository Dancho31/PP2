# Example 1: Loop through list
fruits = ["apple", "banana", "cherry"]
for fruit in fruits:
    print(fruit)
# Output: apple banana cherry

# Example 2: Loop with range
for i in range(3):
    print(i)
# Output: 0 1 2

# Example 3: Loop through string
word = "hello"
for letter in word:
    print(letter)
# Output: h e l l o

# Example 4: Count 1 to 5
for number in range(1, 6):
    print(number)
# Output: 1 2 3 4 5

# Example 5: Even numbers
for i in range(0, 10, 2):
    print(i)
# Output: 0 2 4 6 8
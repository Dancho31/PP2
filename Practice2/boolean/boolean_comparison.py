# Example 1: Compare numbers
print(5 > 3)   # True
print(5 == 3)  # False

# Example 2: Compare strings
print("cat" == "cat")   # True
print("cat" == "dog")   # False

# Example 3: Check range
age = 20
print(18 <= age <= 30)  # True

# Example 4: List comparison
a = [1, 2]
b = [1, 2]
print(a == b)  # True

# Example 5: Not equal
print(10 != 5)  # True